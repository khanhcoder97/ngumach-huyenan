    # --- 2. Timing + SRT (copies, SHA-verified against the campaign manifest).
    timing_src = DELIVERIES / "CIN_005" / "CIN_005_timing_v1.json"
    srt_src = DELIVERIES / "CIN_005" / "CIN_005_vi.srt"
