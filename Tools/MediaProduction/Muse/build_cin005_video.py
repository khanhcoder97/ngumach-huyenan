            "3 separate 16:9 keyframes, one per shot, 640x360 each.",
            "S02 roof palette (blue-grey) drifts from S01 red roofs; "
            "art-direction lock required at final picture.",
            "S01/S03 carry tiny illegible glyph-like marks on small signs; "
            "S02 carries one extra generic unidentified figure (not a "
            "named character, no canon conflict).",
