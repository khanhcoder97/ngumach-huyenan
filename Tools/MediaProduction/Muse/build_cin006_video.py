def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def is_lfs_pointer(path: Path) -> bool:
    with open(path, "rb") as f:
        return f.read(200).startswith(b"version https://git-lfs.github.com")


def check(cond, msg):
    if not cond:
        failures.append(msg)
        print("FAIL: " + msg)


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        print("FAILED:", " ".join(str(c) for c in cmd), file=sys.stderr)
        print(r.stdout, r.stderr, file=sys.stderr)
        sys.exit(1)
    return r


def probe_video(path: Path):
    out = run(["ffprobe", "-v", "error", "-count_frames",
               "-select_streams", "v:0",
               "-show_entries",
               "stream=codec_name,width,height,avg_frame_rate,"
               "nb_read_frames,duration",
               "-show_entries", "format=duration",
               "-of", "json", str(path)])
    return json.loads(out.stdout)


SRT_TIME_RE = re.compile(
    r"^\d\d:\d\d:\d\d,\d\d\d --> \d\d:\d\d:\d\d,\d\d\d$")


def count_srt_cues(text: str):
    blocks = [b.strip() for b in re.split(r"\n\s*\n", text.strip())
              if b.strip()]
    if not blocks:
        return None
    count = 0
    for block in blocks:
        lines = block.splitlines()
        if len(lines) < 3 or not lines[0].strip().isdigit():
            return None
        if not SRT_TIME_RE.match(lines[1].strip()):
            return None
        count += 1
    return count


def mean_abs_diff(img_a: Image.Image, img_b: Image.Image) -> float:
    a = img_a.convert("RGB")
    b = img_b.convert("RGB")
    if a.size != b.size:
        return float("inf")
    pa = list(a.getdata())
    pb = list(b.getdata())
    total = 0
    for (r1, g1, b1), (r2, g2, b2) in zip(pa, pb):
        total += abs(r1 - r2) + abs(g1 - g2) + abs(b1 - b2)
    return total / (len(pa) * 3)


def extract_frame(video: Path, seconds: float, out: Path):
    run(["ffmpeg", "-y", "-v", "error", "-ss", str(seconds),
         "-i", str(video), "-frames:v", "1", str(out)])


def extract_frame_n(video: Path, n: int, out: Path):
    # Exact frame by index (timestamps near EOF can miss by rounding).
    run(["ffmpeg", "-y", "-v", "error", "-i", str(video),
         "-vf", f"select='eq(n\\,{n})'", "-frames:v", "1", str(out)])

